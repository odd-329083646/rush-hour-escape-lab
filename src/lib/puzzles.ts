// פונקציית עזר שמתרגמת את הרשימה המקוצרת לרשימה מלאה עבור המשחק
function inflateCars(shortCars: ShortCar[]): Car[] {
  return shortCars.map((c) => {
    const defs = CAR_DEFAULTS[c.id] || { name: `Car ${c.id}`, color: "var(--car-slate)", len: 2 };
    return {
      ...c,
      name: defs.name,
      color: defs.color,
      len: defs.len,
    };
  });
}

